    def close(self):
        super().close()
        if self.is_open:
            self._log_resource_snapshot("close_started")
            try:
                if getattr(self, "metricsReadySemaphore", None) is not None:
                    try:
                        self.metricsReadySemaphore.release()
                    except Exception:
                        pass
                if getattr(self, "controlSemaphore", None) is not None:
                    try:
                        self.controlSemaphore.release()
                    except Exception:
                        pass

                if getattr(self, "selector", None) is not None:
                    try:
                        for key in list(self.selector.get_map().values()):
                            try:
                                self.selector.unregister(key.fileobj)
                            except Exception:
                                pass
                    finally:
                        try:
                            self.selector.close()
                        except Exception:
                            pass

                if getattr(self, "sim_process", None) is not None:
                    if self.sim_process.poll() is None:
                        self.sim_process.terminate()
                        try:
                            self.sim_process.wait(timeout=5)
                        except subprocess.TimeoutExpired:
                            self.sim_process.kill()
                            self.sim_process.wait(timeout=5)

                    for stream_name in ("stdout", "stderr"):
                        stream = getattr(self.sim_process, stream_name, None)
                        if stream is not None:
                            try:
                                stream.close()
                            except Exception:
                                pass

                if getattr(self, "datalake", None) is not None:
                    try:
                        if getattr(self.datalake, "connection", None) is not None:
                            self.datalake.release_connection()
                    except Exception:
                        pass

                for sem_name in ("controlSemaphore", "metricsReadySemaphore"):
                    sem = getattr(self, sem_name, None)
                    if sem is None:
                        continue
                    try:
                        sem.close()
                    except Exception:
                        pass
                    try:
                        sem.unlink()
                    except Exception:
                        pass
            finally:
                self.selector = None
                self.sim_process = None
                self.controlSemaphore = None
                self.metricsReadySemaphore = None
                self.action_controller = None
                self.datalake = None
                self._csv_read_state = {}
                self.is_open = False
                self._log_resource_snapshot("close_completed")

    def __del__(self):
        if self.is_open:
            self.close()
